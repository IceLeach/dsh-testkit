param(
    [Parameter(Mandatory = $true)]
    [string]$Name,
    [string]$Source = ''
)

$ErrorActionPreference = 'Stop'

$root = $PSScriptRoot
$testHome = Join-Path $root 'home'
$profileDir = Join-Path $testHome 'profiles\headless'
$nm = Join-Path $profileDir 'node_modules'

# 默认从 plugins/packages 取；-Source 可指向任意目录
$src = Join-Path $root '..\plugins\packages'
if ($Source -ne '') {
    $src = Join-Path $root $Source
}

# 包可以直接在 $src 下，也可以在 $src/packages 下（monorepo 结构）
$pkgBase = $src
$packagesDir = Join-Path $src 'packages'
if (Test-Path -LiteralPath $packagesDir) {
    $pkgBase = $packagesDir
}

if (-not (Test-Path -LiteralPath $profileDir)) {
    throw "隔离 profile 不存在，先跑 init.ps1"
}

New-Item -ItemType Directory -Path $nm -Force | Out-Null

# 有共享包 core 就一起复制；没有就只处理插件本身
$pkgDirs = @($Name)
$coreDir = Join-Path $pkgBase 'core'
if (Test-Path -LiteralPath $coreDir) {
    $pkgDirs = @('core') + $pkgDirs
}

$plugins = @()
foreach ($dir in $pkgDirs) {
    $from = Join-Path $pkgBase $dir
    if (-not (Test-Path -LiteralPath $from)) {
        throw "找不到包：$from"
    }

    $pkgJson = Get-Content -Raw -LiteralPath (Join-Path $from 'package.json') -Encoding UTF8 | ConvertFrom-Json
    $dstName = $pkgJson.name
    if (-not $dstName) { throw "package.json 缺少 name：$from" }

    $to = Join-Path $nm $dstName
    if (Test-Path -LiteralPath $to) {
        Remove-Item -LiteralPath $to -Recurse -Force
    }
    Copy-Item -LiteralPath $from -Destination $to -Recurse -Force

    # 只有声明了 dsh.bundle.patch 的才是插件；共享包只复制，不插进 patch
    if ($pkgJson.dsh -and $pkgJson.dsh.bundle -and $pkgJson.dsh.bundle.patch) {
        $plugins += $dstName
    }
}

$listFile = Join-Path $profileDir 'installed-plugins.txt'
$list = @()
if (Test-Path -LiteralPath $listFile) {
    $list = @(Get-Content -LiteralPath $listFile -Encoding UTF8)
}
foreach ($n in $plugins) {
    if ($list -notcontains $n) { $list += $n }
}
Set-Content -LiteralPath $listFile -Value $list -Encoding UTF8

$yaml = @('# generated by testkit/install-plugin.ps1', '- insert:')
foreach ($n in $list) {
    $yaml += "    - id: $n"
    $yaml += "      name: $n"
}
Set-Content -LiteralPath (Join-Path $profileDir 'cordis.patch.yml') -Value $yaml -Encoding UTF8

Write-Output "installed: $($plugins -join ', ')"
Get-Content -LiteralPath (Join-Path $profileDir 'cordis.patch.yml')
